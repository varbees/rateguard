#!/usr/bin/env python3
"""Writes conformance/usd_budget_vectors.json: the shared oracle for USD budgets (0.6).

Independent of all three SDKs. The two float steps are DEFINED as IEEE-754 double
operations (identical in Go, Node and Python):
  usd_to_micro(usd)      = floor(usd * 1e6 + 0.5)
  rate_micro_per_m(p1k)  = floor(p1k * 1e9 + 0.5)       # USD per 1K tokens -> micro-USD per 1M tokens
Everything after that is exact integer arithmetic, done here with Python ints:
  reserve = ceil((prompt * max(in, cacheWrite, cacheWriteLong) + output * out) / 1e6)
  cost    = ceil((fresh*in + read*cacheRead + (write-writeLong)*cacheWrite + writeLong*cacheWriteLong + output*out) / 1e6)
with cacheRead/cacheWrite falling back to the input rate and cacheWriteLong to cacheWrite when absent or zero.
"""
import json, math, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
PRICES = {
    # Frozen inside the file, so a price-table update never changes a vector.
    "vec-full": {"promptUSDPer1K": 0.003, "completionUSDPer1K": 0.015, "cacheReadUSDPer1K": 0.0003, "cacheWriteUSDPer1K": 0.00375, "cacheWriteLongTTLUSDPer1K": 0.006},
    "vec-nocache": {"promptUSDPer1K": 0.00015, "completionUSDPer1K": 0.0006},
    "vec-tiny": {"promptUSDPer1K": 0.0000001, "completionUSDPer1K": 0.0000004},
    "vec-pricey": {"promptUSDPer1K": 0.15, "completionUSDPer1K": 0.6},
}

def usd_to_micro(usd: float) -> int:
    return math.floor(usd * 1e6 + 0.5)

def rate(p1k) -> int:
    return math.floor(p1k * 1e9 + 0.5) if p1k else 0

def rates(price: dict) -> dict:
    inp = rate(price["promptUSDPer1K"])
    out = rate(price["completionUSDPer1K"])
    cr = rate(price.get("cacheReadUSDPer1K")) or inp
    cw = rate(price.get("cacheWriteUSDPer1K")) or inp
    cwl = rate(price.get("cacheWriteLongTTLUSDPer1K")) or cw
    return {"input": inp, "output": out, "cacheRead": cr, "cacheWrite": cw, "cacheWriteLongTTL": cwl}

def ceil_micro(n: int) -> int:
    return -(-n // 1_000_000)

def reserve(r: dict, prompt: int, output: int) -> int:
    return ceil_micro(prompt * max(r["input"], r["cacheWrite"], r["cacheWriteLongTTL"]) + output * r["output"])

def cost(r: dict, u: dict) -> int:
    read = max(u.get("cacheReadTokens", 0), 0)
    write = max(u.get("cacheWriteTokens", 0), 0)
    wl = min(max(u.get("cacheWriteLongTTLTokens", 0), 0), write)
    fresh = max(u["inputTokens"] - read - write, 0)
    return ceil_micro(fresh * r["input"] + read * r["cacheRead"] + (write - wl) * r["cacheWrite"] + wl * r["cacheWriteLongTTL"] + u["outputTokens"] * r["output"])

def key(scope, tenant, customer, provider, model):
    cust = f":customer={customer}" if customer else ""
    if scope == "tenant":
        return f"{tenant}:usd"
    if scope == "model":
        return f"{tenant}{cust}:{provider}:{model or 'default'}:usd"
    return f"{tenant}{cust}:usd"

usd_cases = [0.1, 5.0, 1.23456789, 2.5e-7, 5e-7, 0.0000015, 100.0, 0.0]
reserve_cases = [
    ("vec-full", 10_000, 1_000), ("vec-full", 0, 4096), ("vec-nocache", 1_000, 1_000),
    ("vec-tiny", 3, 2), ("vec-tiny", 1, 0), ("vec-pricey", 200_000, 32_768),
]
cost_cases = [
    ("vec-full", {"inputTokens": 10_000, "outputTokens": 500}),
    ("vec-full", {"inputTokens": 10_000, "outputTokens": 500, "cacheReadTokens": 6_000, "cacheWriteTokens": 3_000, "cacheWriteLongTTLTokens": 1_000}),
    ("vec-full", {"inputTokens": 100, "outputTokens": 0, "cacheReadTokens": 400}),  # read > input: fresh clamps to 0
    ("vec-nocache", {"inputTokens": 5_000, "outputTokens": 700, "cacheReadTokens": 1_000, "cacheWriteTokens": 500}),
    ("vec-tiny", {"inputTokens": 7, "outputTokens": 1}),
    ("vec-pricey", {"inputTokens": 123_456, "outputTokens": 7_890}),
]
key_cases = [(s, "t1", c, "openai", m) for s in ("tenant", "customer", "model") for c in ("", "acme") for m in ("gpt-x", "")]

doc = {
    "description": "USD budgets (RateGuard 0.6): money conversion, reservation, settlement, keys and a hard-stop sequence. All three SDKs replay this file. Generated by scripts/gen_usd_budget_vectors.py; edit that, not this.",
    "prices": PRICES,
    "usd_to_micro": [{"usd": u, "micro": usd_to_micro(u)} for u in usd_cases],
    "micro_rates": [{"price": p, "rates": rates(PRICES[p])} for p in PRICES],
    "reserve": [{"price": p, "promptTokens": a, "outputTokens": b, "micro": reserve(rates(PRICES[p]), a, b)} for p, a, b in reserve_cases],
    "cost": [{"price": p, "usage": u, "micro": cost(rates(PRICES[p]), u)} for p, u in cost_cases],
    "keys": [{"scope": s, "tenant": t, "customer": c, "provider": pv, "model": m, "key": key(s, t, c, pv, m)} for s, t, c, pv, m in key_cases],
    # A day limit of 1,000 micro-USD, hard-stop. Reservations follow the token-budget rule: reserve
    # min(estimate, remaining); deny only when nothing remains.
    "sequence": {
        "dayLimitMicro": 1000,
        "steps": [
            {"op": "reserve", "id": "a", "estimate": 600, "allowed": True, "reserved": 600, "remaining": 400},
            {"op": "reserve", "id": "b", "estimate": 600, "allowed": True, "reserved": 400, "remaining": 0},
            {"op": "reserve", "id": "c", "estimate": 1, "allowed": False},
            {"op": "commit", "id": "a", "micro": 300},
            {"op": "check", "remaining": 300},
            {"op": "release", "id": "b"},
            {"op": "check", "remaining": 700},
            {"op": "commit", "id": None, "micro": 700},
            {"op": "check", "remaining": 0, "allowed": False},
        ],
    },
}
out = ROOT / "conformance/usd_budget_vectors.json"
out.write_text(json.dumps(doc, indent=2) + "\n")
print(f"wrote {out.relative_to(ROOT)}")
