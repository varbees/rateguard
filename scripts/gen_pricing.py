#!/usr/bin/env python3
"""Generate the three SDKs' built-in price tables from conformance/pricing.json.

    python3 scripts/gen_pricing.py           rewrite the generated files
    python3 scripts/gen_pricing.py --check   exit 1 if a generated file has
                                             drifted, a row is past its
                                             priceChangesOn date, or the table
                                             was last reviewed > 90 days ago

Why generated rather than hand-copied: until 0.5.3 each SDK carried its own
copy of a 14-row table. The copies agreed with each other and were wrong
together — three rows had drifted from the vendor pages and none of the
current Claude, GPT or Gemini models were present, so they priced at $0 in
spend receipts and FOCUS exports. One file, one review date, one place to fix.

Keys are the normalised model ID (the same normalisation every SDK applies at
lookup), so a provider-reported dated snapshot finds its row. A row marked
exactOnly keeps its literal ID: gpt-4o-2024-05-13 is priced above gpt-4o and
must never be reached by stripping its date.
"""
from __future__ import annotations

import argparse
import datetime as dt
import json
import re
import shutil
import subprocess
import sys
from decimal import Decimal
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "conformance" / "pricing.json"
GO = ROOT / "packages/sdk-go/pricing_table_gen.go"
TS = ROOT / "packages/sdk-node/src/core/pricing-table.ts"
PY = ROOT / "packages/sdk-python/rateguard/core/pricing_table.py"
MAX_AGE_DAYS = 90

ISO_DATE = re.compile(r"-\d{4}-\d{2}-\d{2}$")
COMPACT_DATE = re.compile(r"-\d{8}$")
MONTH_YEAR = re.compile(r"-\d{2}-\d{4}$")


def normalize(model: str) -> str:
    """Mirror of normalizeModelId in every SDK. Keep them in step."""
    m = model.strip().lower()
    while True:
        orig = m
        m = MONTH_YEAR.sub("", COMPACT_DATE.sub("", ISO_DATE.sub("", m)))
        for suffix in ("-preview", "-latest", "-exp"):
            if m.endswith(suffix):
                m = m[: -len(suffix)]
        if m == orig:
            return m


def per_1k(per_1m: float) -> str:
    """USD per 1M -> per 1K as an exact decimal literal (no 0.30000000000000004)."""
    d = Decimal(str(per_1m)) / 1000
    s = format(d.normalize(), "f")
    return s if "." in s else s + ".0"


def rows() -> tuple[str, list[dict]]:
    doc = json.loads(SOURCE.read_text())
    out: dict[str, dict] = {}
    for m in doc["models"]:
        key = m["id"] if m.get("exactOnly") else normalize(m["id"])
        if key in out:
            raise SystemExit(f"gen_pricing: two rows share the key {key!r}")
        lc = m.get("longContext")
        out[key] = {
            "key": key,
            "id": m["id"],
            "prompt": per_1k(m["input"]),
            "completion": per_1k(m["output"]),
            "longAbove": lc["aboveTokens"] if lc else 0,
            "longPrompt": per_1k(lc["input"]) if lc else "0.0",
            "longCompletion": per_1k(lc["output"]) if lc else "0.0",
        }
    return doc["lastReviewed"], [out[k] for k in sorted(out)]


HEADER = "GENERATED by scripts/gen_pricing.py from conformance/pricing.json. Do not edit."


def gofmt(src: str) -> str:
    """Format generated Go the way gofmt would, so `gofmt -l` stays clean.
    Falls back to the raw text when Go is not installed; the CI job that runs
    --check installs Go first."""
    if shutil.which("gofmt") is None:
        return src
    return subprocess.run(["gofmt"], input=src, capture_output=True, text=True, check=True).stdout


def render_go(reviewed: str, table: list[dict]) -> str:
    lines = ["// Code generated by scripts/gen_pricing.py; DO NOT EDIT.", f"// {HEADER}", "",
             "package rateguard", "",
             "// BuiltinPricingReviewed is the day the vendor pages behind the built-in",
             "// price table were last read.",
             f'const BuiltinPricingReviewed = "{reviewed}"', "",
             "var builtinPricing = map[string]builtinPrice{"]
    for r in table:
        lines.append(
            f'\t"{r["key"]}": {{PromptUSDPer1K: {r["prompt"]}, CompletionUSDPer1K: {r["completion"]}, '
            f'LongAboveTokens: {r["longAbove"]}, LongPromptUSDPer1K: {r["longPrompt"]}, '
            f'LongCompletionUSDPer1K: {r["longCompletion"]}}},'
        )
    lines.append("}")
    return gofmt("\n".join(lines) + "\n")


def render_ts(reviewed: str, table: list[dict]) -> str:
    lines = [f"// {HEADER}", "",
             "export interface BuiltinPrice {",
             "  promptUSDPer1K: number;",
             "  completionUSDPer1K: number;",
             "  /** Prompts longer than this pay the long rates; 0 means no long tier. */",
             "  longAboveTokens: number;",
             "  longPromptUSDPer1K: number;",
             "  longCompletionUSDPer1K: number;",
             "}", "",
             "/** The day the vendor pages behind the built-in price table were last read. */",
             f"export const BUILTIN_PRICING_REVIEWED = '{reviewed}';", "",
             "export const BUILTIN_PRICING: Readonly<Record<string, BuiltinPrice>> = {"]
    for r in table:
        lines.append(
            f"  '{r['key']}': {{ promptUSDPer1K: {r['prompt']}, completionUSDPer1K: {r['completion']}, "
            f"longAboveTokens: {r['longAbove']}, longPromptUSDPer1K: {r['longPrompt']}, "
            f"longCompletionUSDPer1K: {r['longCompletion']} }},"
        )
    lines.append("};")
    return "\n".join(lines) + "\n"


def render_py(reviewed: str, table: list[dict]) -> str:
    lines = [f'"""{HEADER}"""', "", "from __future__ import annotations", "",
             "# The day the vendor pages behind the built-in price table were last read.",
             f'BUILTIN_PRICING_REVIEWED = "{reviewed}"', "",
             "# key: (prompt_usd_per_1k, completion_usd_per_1k,",
             "#       long_above_tokens, long_prompt_usd_per_1k, long_completion_usd_per_1k)",
             "BUILTIN_PRICING: dict[str, tuple[float, float, int, float, float]] = {"]
    for r in table:
        lines.append(
            f'    "{r["key"]}": ({r["prompt"]}, {r["completion"]}, {r["longAbove"]}, '
            f'{r["longPrompt"]}, {r["longCompletion"]}),'
        )
    lines.append("}")
    return "\n".join(lines) + "\n"


def freshness_problems(today: dt.date) -> list[str]:
    doc = json.loads(SOURCE.read_text())
    problems = []
    reviewed = dt.date.fromisoformat(doc["lastReviewed"])
    if (today - reviewed).days > MAX_AGE_DAYS:
        problems.append(
            f"price table last reviewed {reviewed}, {(today - reviewed).days} days ago (limit {MAX_AGE_DAYS})"
        )
    for m in doc["models"]:
        changes = m.get("priceChangesOn")
        if changes and today >= dt.date.fromisoformat(changes):
            problems.append(f"{m['id']}: the vendor announced new rates from {changes}; re-read {m['sourceUrl']}")
        if not m.get("sourceUrl", "").startswith("https://") or not m.get("seenAt"):
            problems.append(f"{m['id']}: missing sourceUrl or seenAt")
    return problems


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()

    reviewed, table = rows()
    want = {GO: render_go(reviewed, table), TS: render_ts(reviewed, table), PY: render_py(reviewed, table)}

    if not args.check:
        for path, text in want.items():
            path.write_text(text)
        print(f"gen_pricing: wrote {len(table)} rows into {len(want)} SDK tables")
        return 0

    failed = False
    for path, text in want.items():
        if not path.exists() or path.read_text() != text:
            print(f"gen_pricing: {path.relative_to(ROOT)} is out of date; run python3 scripts/gen_pricing.py")
            failed = True
    for p in freshness_problems(dt.date.today()):
        print(f"gen_pricing: {p}")
        failed = True
    if not failed:
        print(f"gen_pricing: {len(table)} rows in sync, reviewed {reviewed}")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
